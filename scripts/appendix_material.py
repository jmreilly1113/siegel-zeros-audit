"""Paper prep 4, Task 8: appendix material copied from existing results (read-only on results/; new files only).

Usage: python -I scripts/appendix_material.py <repo root> <out dir>
"""
import hashlib, os, re, sys

root, out = sys.argv[1:3]
R = os.path.join(root, 'results')
A = os.path.join(out, 'appendix')
os.makedirs(A, exist_ok=True)
rel = lambda p: os.path.relpath(p, root).replace(os.sep, '/')
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
read = lambda p: open(p, encoding='utf-8', errors='replace').read()
write = lambda name, text: open(os.path.join(A, name), 'w', encoding='utf-8', newline='\n').write(text)
NINE = ['OptimalMaxCut', 'UniqueGamesTheorem', 'VertexCover', 'KaplanskyFinitelyPresented', 'GroupRingDeterminant', 'Laughlin',
        'BinPackingGap', 'IndependentSets', 'PerfectCompleteness']
RESULT = re.compile(r'Illegal axiom detected|do not match|kernel accepts|kernel rejected|kernel rejects|Your solution is okay|'
                    r'COMPARATOR EXIT CODE|overflowed its stack|nanoda exited|uncaught exception|DURATION_SECONDS')

# ---- Appendix A: longtable from corpus-189.tsv (read only) ----
tsv = os.path.join(R, '2026-10-20-paper-prep-3', 'corpus-189.tsv')
rows = [l.rstrip('\n').split('\t') for l in open(tsv, encoding='utf-8')][1:]
assert len(rows) == 189
esc = lambda s: s.replace('\\', r'\textbackslash{}').replace('_', r'\_').replace('&', r'\&').replace('#', r'\#')
short = {'ACCEPT': 'accept', 'CRASH (stack overflow)': 'crash', '': '--'}
lines = [f'% Generated by scripts/appendix_material.py from {rel(tsv)} (sha256 {sha(tsv)}); do not edit by hand.',
         r'\begin{longtable}{@{}llllll@{}}', r'\toprule', r'Config & Family & Commit & Lean & nanoda 3a24072 & nanoda f67473b \\',
         r'\midrule', r'\endhead']
for r in rows:
    lines.append(f'{esc(r[0])} & {r[1]} & {r[2]} & {short.get(r[3].replace("ACCEPT", "ACCEPT"), r[3].lower())} & '
                 f'{short.get(r[4], r[4])} & {short.get(r[5], r[5])} \\\\')
lines += [r'\bottomrule', r'\end{longtable}']
write('appendix-a.tex', '\n'.join(lines) + '\n')

# ---- Appendix C ----
def block(path, title, extra=''):
    t = read(path)
    res = [l for l in t.splitlines() if RESULT.search(l)]
    return (f'# {title}\n# source: {rel(path)} (sha256 {sha(path)}); copied 2026-10-21, unchanged\n{extra}'
            f'\n== config and diff against the shipped config (as printed in the log)\n' +
            t.split('== clone:')[0].rstrip() + '\n\n== Comparator result lines\n' + '\n'.join(res) + '\n')

c1 = os.path.join(R, '2026-10-11-corpus-headline', 'DirichletSevenEighths-nanoda.log')
write('C1-nanoda-enabling-config-diff.txt', block(c1, 'Representative nanoda-enabling config: the corpus copy differs from the shipped config only in enable_nanoda'))
c2 = os.path.join(R, '2026-10-11-corpus-pilot', 'SiegelZeros-control-noChoice.log')
write('C2-negcontrol-classical-choice-removed.txt', block(c2, 'Negative control (a): Classical.choice removed from permitted_axioms (SiegelZeros, adc7f12). Expected: rejected'))
c3 = os.path.join(R, '2026-10-11-corpus-pilot', 'SiegelZeros-control-altered.log')
c3d = os.path.join(R, '2026-10-11-corpus-pilot', 'SiegelZeros-control-altered.challenge-diff.txt')
write('C3-negcontrol-altered-hypothesis.txt', block(c3, 'Negative control (b): challenge copy with one hypothesis altered (3 <= q -> 2 <= q) (SiegelZeros, adc7f12). Expected: statements do not match',
                                                    f'# challenge diff: {rel(c3d)} (sha256 {sha(c3d)}):\n' + read(c3d)))
c4d = os.path.join(R, '2026-10-20-paper-prep', 'wsl', 'task2d-control-diff.txt')
parts = [f'# Negative control (c): challenge-declared axiom used by the solution (HarmonicGrowth, fd4aeeb). Expected: illegal axiom\n'
         f'# solution source diff: {rel(c4d)} (sha256 {sha(c4d)}):\n' + read(c4d)]
for v in ('shipped', 'nanoda'):
    p = os.path.join(R, '2026-10-20-paper-prep', 'wsl', f'task2d-negcontrol-{v}.log')
    parts.append(block(p, f'run with {v} settings'))
write('C4-negcontrol-challenge-declared-axiom.txt', '\n'.join(parts))

# ---- Appendix D: crash excerpts ----
corpus_logs = {}
for d in ['2026-10-11-corpus-headline'] + [f'2026-10-12-corpus-remainder/{b}' for b in sorted(os.listdir(os.path.join(R, '2026-10-12-corpus-remainder'))) if b.startswith('batch-')]:
    for n in NINE:
        p = os.path.join(R, d, f'{n}-nanoda.log')
        if os.path.isfile(p):
            corpus_logs[n] = p
D = []
for n in NINE:
    p = corpus_logs[n]
    L = read(p).splitlines()
    i0 = next(i for i, l in enumerate(L) if 'Running nanoda kernel' in l)
    i1 = next(i for i, l in enumerate(L) if 'COMPARATOR EXIT CODE' in l)
    ex = L[i0:i1 + 1]
    if len(ex) > 20:
        keep = [l for l in ex if RESULT.search(l) or 'Running' in l or 'thread' in l]
        ex = keep[:20]
    pf = os.path.join(R, '2026-10-20-nanoda-postfix-f67473b', f'{n}-postfix.log')
    acc = [l for l in read(pf).splitlines() if re.search(r'nanoda kernel accepts|Lean default kernel accepts|Your solution is okay|COMPARATOR EXIT CODE|DURATION', l)]
    txt = (f'# {n}: nanoda 3a24072 crash (corpus run) and nanoda f67473b accept (unofficial batch)\n'
           f'# 3a24072 log: {rel(p)} (sha256 {sha(p)}), lines {i0 + 1}-{i1 + 1} (excerpt, {len(ex)} lines)\n' + '\n'.join(ex) +
           f'\n\n# f67473b log: {rel(pf)} (sha256 {sha(pf)})\n' + '\n'.join(acc) + '\n')
    write(f'D-{n}.txt', txt)
    D.append((n, len(ex)))
print('appendix written:', sorted(os.listdir(A)))
print('D excerpt lengths:', D)
